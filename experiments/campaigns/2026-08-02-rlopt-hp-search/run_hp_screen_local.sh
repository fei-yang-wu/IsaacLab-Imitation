#!/usr/bin/env bash
# Local RLOpt hyperparameter screen for the G1 v2 low-level tracker.
#
# Ten arms, each a 50M-frame block at 12288 envs, run sequentially on the
# workstation GPU. Every arm differs from `b0_baseline` in exactly one knob so
# the screen attributes a change to a cause.
#
# The default is 12 steps, not 24: on the cluster the 24-step job was clearly
# slower per frame and per wall-clock second, and 12 steps is also the reference
# geometry, so b0 is the cluster recipe verbatim. At a fixed 50M frames it
# additionally buys 340 iterations instead of 170. Only `a8_r24_matched`
# rebatches, and it holds the frame budget by halving its iteration count.
#
# The arms exist because a 3.5B-frame reference run (wandb
# g1-lafan1-strict/01sktm46) showed two things:
#
#   1. The adaptive-KL rule fires per minibatch, so it moves the LR up to 80x
#      per iteration here. Over that run the iteration-mean KL was 0.0136 and
#      sat inside the [0.005, 0.02] dead band 100% of the time -- evaluated on
#      the mean, the rule would never have fired at all. Every LR movement came
#      from minibatch sampling noise, and the log-LR is a zero-drift random
#      walk (mean move +0.000, sd 2.55 in units of log 1.5) spanning 58x.
#   2. The entropy bonus dominates the actor loss (loss_entropy -0.0416 vs
#      loss_objective -0.0093), holding sigma near 0.32 rad. That noise alone
#      accounts for essentially all of the action_rate_l2 penalty (-0.53, the
#      largest-magnitude reward term) and floors tracking precision.
#
# This is a SCREEN, not a result. 50M frames at 12 steps is 340 iterations; the
# reference run needs ~1200 to reach an episode length of 400. It ranks early
# progress and optimizer health. Nothing here is reportable.
#
# Do not edit this file while a screen is running: bash reads a script lazily by
# byte offset, so rewriting it mid-run can make the interpreter resume in the
# middle of a different line.
#
# Usage, from the repository root:
#   ./experiments/campaigns/2026-08-02-rlopt-hp-search/run_hp_screen_local.sh
#     -> dry run: prints every arm's exact command and exits.
#   DRY_RUN=0 ./experiments/campaigns/2026-08-02-rlopt-hp-search/run_hp_screen_local.sh
#     -> runs all ten arms (~5-6 h).
#   DRY_RUN=0 ARMS="b0_baseline a2_kl_per_iteration" ...
#     -> runs a subset.
#
# Then aggregate:
#   pixi run -e default python -m \
#     imitation_experiments.lowlevel.aggregate_rlopt_hp_screen \
#     --screen_root logs/rlopt_hp_screen_20260802 \
#     --out logs/rlopt_hp_screen_20260802/screen.md

set -euo pipefail

REPO_ROOT="${REPO_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)}"
cd "${REPO_ROOT}"

DRY_RUN="${DRY_RUN:-1}"
SCREEN_ROOT="${SCREEN_ROOT:-logs/rlopt_hp_screen_20260802}"
SEED="${SEED:-0}"

# --- Fixed geometry: identical for every arm, and checked by the aggregator ---
NUM_ENVS="${NUM_ENVS:-12288}"
ROLLOUT_STEPS="${ROLLOUT_STEPS:-12}"
MAX_ITERATIONS="${MAX_ITERATIONS:-340}"   # x 147,456 = 50,135,040 frames
FRAMES_PER_BATCH=$((NUM_ENVS * ROLLOUT_STEPS))
TOTAL_FRAMES=$((MAX_ITERATIONS * FRAMES_PER_BATCH))

# --- Task + frozen latent recipe ---------------------------------------------
# Same det-SR h=10 z=256 encoder and corrected 40-motion LAFAN1 manifest the
# paper-facing arms use. The encoder is frozen: this screens the RL optimizer,
# not representation learning.
TASK_NAME="${TASK_NAME:-Isaac-Imitation-G1-v2}"
MANIFEST_PATH="${MANIFEST_PATH:-./data/lafan1/manifests/g1_lafan1_manifest.json}"
EXPECTED_MANIFEST_SHA256="d972c37c41dadbb68c30fc456a9dc9c1bd6d30ed0b7aa9d34b1797472c945db8"
# Auto-derivation from the manifest entries lands on a path that holds no
# transitions and fails deep inside the buffer build with "Computed
# non-positive capacity"; pass the cache explicitly.
DATASET_PATH="${DATASET_PATH:-./data/lafan1/zarr/g1_hl_diffsr}"
ENCODER_CKPT="${ENCODER_CKPT:-logs/downloaded_checkpoints/lafan1_latent_deterministic_5b_seed0/skill_encoder/best.pt}"
HORIZON_STEPS=10

# --- Arms --------------------------------------------------------------------
# The table lives in arms.sh so this launcher and the ICE one cannot drift; see
# that file for what each arm isolates and why.
# shellcheck source=./arms.sh
source "$(dirname "${BASH_SOURCE[0]}")/arms.sh"
ARM_SPECS=("${HP_SCREEN_ARM_SPECS[@]}")
ALL_ARM_NAMES=("${HP_SCREEN_ALL_ARM_NAMES[@]}")
ARMS="${ARMS:-${ALL_ARM_NAMES[*]}}"

# --- Preflight ---------------------------------------------------------------
# Fail before spending hours of GPU, not after.
fail() { echo "[FATAL] $*" >&2; exit 1; }

[[ -f "${MANIFEST_PATH}" ]] || fail "manifest not found: ${MANIFEST_PATH}"
actual_sha="$(sha256sum "${MANIFEST_PATH}" | cut -d' ' -f1)"
[[ "${actual_sha}" == "${EXPECTED_MANIFEST_SHA256}" ]] || fail \
    "manifest sha256 mismatch: expected ${EXPECTED_MANIFEST_SHA256}, got ${actual_sha}"
[[ -d "${DATASET_PATH}" ]] || fail "dataset cache not found: ${DATASET_PATH}"
[[ -f "${ENCODER_CKPT}" ]] || fail "encoder checkpoint not found: ${ENCODER_CKPT}"

for name in ${ARMS}; do
    found=0
    for known in "${ALL_ARM_NAMES[@]}"; do
        [[ "${name}" == "${known}" ]] && found=1 && break
    done
    [[ "${found}" == 1 ]] || fail "unknown arm '${name}'. Known: ${ALL_ARM_NAMES[*]}"
done

echo "[INFO] screen root : ${SCREEN_ROOT}"
echo "[INFO] geometry    : ${NUM_ENVS} envs x ${ROLLOUT_STEPS} steps = ${FRAMES_PER_BATCH} frames/iter"
echo "[INFO] budget      : ${MAX_ITERATIONS} iterations = ${TOTAL_FRAMES} frames per arm"
echo "[INFO] arms        : ${ARMS}"
echo "[INFO] dry run     : ${DRY_RUN}"
echo

run_arm() {
    local name="$1" description="$2" overrides="$3"
    local arm_dir="${SCREEN_ROOT}/${name}"

    # Refuse to silently merge a new run into a finished arm: the aggregator
    # would read both runs' scalars as one curve.
    if [[ "${DRY_RUN}" == "0" && -e "${arm_dir}/arm.json" ]]; then
        fail "${arm_dir} already holds a completed arm; move it aside or pick a new SCREEN_ROOT"
    fi

    # A ROLLOUT_STEPS=N pseudo-override rebatches this arm. The frame budget is
    # held constant by scaling the iteration count against it, so the arm still
    # sees the same 50M frames -- that is what makes it comparable at all.
    local arm_rollout="${ROLLOUT_STEPS}" arm_iterations="${MAX_ITERATIONS}"
    local hydra_overrides=""
    for token in ${overrides}; do
        if [[ "${token}" == ROLLOUT_STEPS=* ]]; then
            arm_rollout="${token#ROLLOUT_STEPS=}"
        else
            hydra_overrides+="${token} "
        fi
    done
    overrides="${hydra_overrides% }"
    local arm_frames_per_batch=$((NUM_ENVS * arm_rollout))
    if (( TOTAL_FRAMES % arm_frames_per_batch != 0 )); then
        fail "${name}: ${TOTAL_FRAMES} frames is not a whole number of "\
"${arm_frames_per_batch}-frame iterations; pick a rollout length that divides it"
    fi
    arm_iterations=$((TOTAL_FRAMES / arm_frames_per_batch))

    local -a cmd=(
        env TERM=xterm OMNI_KIT_ACCEPT_EULA=YES PYTHONUNBUFFERED=1
        HYDRA_FULL_ERROR=1 TORCHDYNAMO_DISABLE=1
        pixi run -e isaaclab python scripts/rlopt/train_physx.py
        --task "${TASK_NAME}" --algo IPMD
        --num_envs "${NUM_ENVS}" --max_iterations "${arm_iterations}" --headless
        --seed "${SEED}"
        --kit_args=--/app/extensions/fsWatcherEnabled=false
        "env.lafan1_manifest_path=${MANIFEST_PATH}"
        "env.dataset_path=${DATASET_PATH}"
        env.refresh_zarr_dataset=false
        # The encoder consumes a 10-frame window (input dim 670 = 10*58 + 10*3
        # + 10*6), so the interface must publish current + 9 future frames.
        env.command_interface.encoder.future_steps=9
        agent.ipmd.command_source=hl_skill
        "agent.ipmd.hl_skill_checkpoint_path=${ENCODER_CKPT}"
        "agent.ipmd.hl_skill_horizon_steps=${HORIZON_STEPS}"
        agent.ipmd.hl_skill_finetune_enabled=false
        agent.ipmd.latent_steps_min=10
        agent.ipmd.latent_steps_max=10
        agent.ipmd.latent_learning.code_period=10
        "agent.collector.frames_per_batch=${arm_rollout}"
        # CSV, not wandb: the screen is local, offline-reproducible from the run
        # directory, and does not belong in the shared training project.
        agent.logger.backend=csv
        "agent.logger.log_dir=${arm_dir}"
        # Every metric every iteration; the aggregator averages a tail and a
        # 170-iteration curve is small.
        --log_interval "${arm_frames_per_batch}"
        agent.save_interval=1000000000
    )
    # shellcheck disable=SC2206
    cmd+=(${overrides})

    echo "=== ${name} ==="
    echo "    ${description}"
    printf '    %s\n' "${overrides}"
    if [[ "${DRY_RUN}" != "0" ]]; then
        printf '    +'; printf ' %q' "${cmd[@]}"; printf '\n\n'
        return 0
    fi

    mkdir -p "${arm_dir}"
    local start_s end_s status=0
    start_s="$(date +%s)"
    "${cmd[@]}" > "${arm_dir}/train.log" 2>&1 || status=$?
    end_s="$(date +%s)"

    # arm.json is what the aggregator discovers, so write it even on failure --
    # a crashed arm should show up in the table as a crashed arm, not vanish.
    local overrides_json=""
    for override in ${overrides}; do
        overrides_json+="\"${override}\", "
    done
    cat > "${arm_dir}/arm.json" <<JSON
{
  "arm": "${name}",
  "description": "${description}",
  "overrides": [${overrides_json%, }],
  "geometry": {
    "num_envs": ${NUM_ENVS},
    "rollout_steps": ${arm_rollout},
    "frames_per_batch": ${arm_frames_per_batch},
    "max_iterations": ${arm_iterations},
    "total_frames": ${TOTAL_FRAMES},
    "seed": ${SEED}
  },
  "task": "${TASK_NAME}",
  "encoder_checkpoint": "${ENCODER_CKPT}",
  "manifest_sha256": "${EXPECTED_MANIFEST_SHA256}",
  "wall_time_s": $((end_s - start_s)),
  "exit_status": ${status}
}
JSON

    if [[ "${status}" != "0" ]]; then
        echo "    [WARN] arm exited ${status}; see ${arm_dir}/train.log"
    else
        echo "    [OK] $(( (end_s - start_s) / 60 )) min -> ${arm_dir}"
    fi
    echo
}

for spec in "${ARM_SPECS[@]}"; do
    name="${spec%%|*}"
    rest="${spec#*|}"
    description="${rest%%|*}"
    overrides="${rest#*|}"
    for requested in ${ARMS}; do
        if [[ "${requested}" == "${name}" ]]; then
            run_arm "${name}" "${description}" "${overrides}"
            break
        fi
    done
done

if [[ "${DRY_RUN}" != "0" ]]; then
    echo "[INFO] dry run only. Re-run with DRY_RUN=0 to execute."
else
    echo "[INFO] screen complete. Aggregate with:"
    echo "  pixi run -e default python -m imitation_experiments.lowlevel.aggregate_rlopt_hp_screen \\"
    echo "    --screen_root ${SCREEN_ROOT} --out ${SCREEN_ROOT}/screen.md"
fi
